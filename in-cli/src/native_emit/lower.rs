    fn code_contains_insns(code: &[u8], insns: &[u32]) -> bool {
        let words: Vec<u32> = code
            .chunks_exact(4)
            .map(|b| u32::from_le_bytes(b.try_into().unwrap()))
            .collect();
        for insn in insns {
            if !words.contains(insn) {
                return false;
            }
        }
        true
    }

